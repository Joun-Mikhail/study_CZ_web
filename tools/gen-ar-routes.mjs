#!/usr/bin/env node
// Generates the Arabic twin of every English route under src/app/ar/.
//
// Each Arabic page re-uses the English page's component (the components read
// the language from the URL), and swaps in Arabic metadata. Run this again
// after adding a new page:  node tools/gen-ar-routes.mjs
//
// Files containing the marker "@custom-ar" are never overwritten — use it for
// Arabic pages that need hand-written metadata (dynamic routes).
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, statSync } from "node:fs";
import { join, relative, dirname, sep } from "node:path";

const APP = "src/app";
const AR = join(APP, "ar");
const SKIP = ["ar", "admin"];

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      if (dir === APP && SKIP.includes(name)) continue;
      walk(full, out);
    } else if (name === "page.tsx" || name === "layout.tsx") {
      out.push(full);
    }
  }
  return out;
}

const has = (src, re) => re.test(src);

function writeIfAllowed(target, content) {
  if (existsSync(target) && readFileSync(target, "utf8").includes("@custom-ar")) return "kept";
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, content);
  return "written";
}

const files = walk(APP).filter((f) => f !== join(APP, "layout.tsx"));
let count = 0;
for (const file of files) {
  // Always forward slashes: on Windows path.relative() returns backslashes,
  // which would end up inside import paths.
  const rel = relative(APP, file).split(sep).join("/"); // e.g. services/page.tsx
  const routeDir = dirname(rel) === "." ? "" : dirname(rel);
  const enPath = routeDir === "" ? "/" : `/${routeDir}/`;
  const importPath = `@/app/${rel.replace(/\.tsx$/, "")}`;
  const src = readFileSync(file, "utf8");
  const isDynamic = routeDir.includes("[");
  const kind = file.endsWith("page.tsx") ? "page" : "layout";

  const lines = [
    "// Generated by tools/gen-ar-routes.mjs — Arabic twin of " + (enPath === "/" ? "/" : enPath),
  ];
  const reexports = ["default"];
  if (has(src, /export (async )?function generateStaticParams/)) reexports.push("generateStaticParams");

  if (has(src, /export const metadata/)) {
    lines.push('import type { Metadata } from "next";');
    lines.push(`import { metadata as en } from "${importPath}";`);
    lines.push('import { arabicMetadata } from "@/i18n/ar-metadata";');
    lines.push(`export { ${reexports.join(", ")} } from "${importPath}";`);
    lines.push(`export const metadata: Metadata = arabicMetadata("${enPath}", en);`);
  } else if (has(src, /export async function generateMetadata/)) {
    lines.push('import type { Metadata } from "next";');
    lines.push(`import { generateMetadata as en } from "${importPath}";`);
    lines.push('import { arabicMetadata } from "@/i18n/ar-metadata";');
    lines.push(`export { ${reexports.join(", ")} } from "${importPath}";`);
    // Build the English path from the route params at request (build) time.
    const paramNames = [...routeDir.matchAll(/\[([^\]]+)\]/g)].map((m) => m[1]);
    const pathExpr = "`" + enPath.replace(/\[([^\]]+)\]/g, (_, n) => "${p." + n + "}") + "`";
    lines.push(
      `export async function generateMetadata(props: { params: Promise<{ ${paramNames
        .map((n) => `${n}: string`)
        .join("; ")} }> }): Promise<Metadata> {`,
      "  const p = await props.params;",
      "  return arabicMetadata(" + pathExpr + ", await en(props));",
      "}"
    );
  } else if (kind === "page" && !isDynamic) {
    lines.push('import type { Metadata } from "next";');
    lines.push('import { arabicMetadata } from "@/i18n/ar-metadata";');
    lines.push(`export { ${reexports.join(", ")} } from "${importPath}";`);
    lines.push(`export const metadata: Metadata = arabicMetadata("${enPath}");`);
  } else {
    lines.push(`export { ${reexports.join(", ")} } from "${importPath}";`);
  }

  const target = join(AR, rel);
  const result = writeIfAllowed(target, lines.join("\n") + "\n");
  if (result === "written") count++;
}
console.log(`Arabic routes: ${count} files written under ${AR}`);
